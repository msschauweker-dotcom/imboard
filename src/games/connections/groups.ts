// CONNECTIONS group bank.
//
// Each group lists ALL reasonable members (more than four), so the generator can
// detect when a word shown for one group would also fit another group on the
// same board. `also` lists extra words that fit the category but we never show.
// `tags` mark groups that must never share a board (overlapping themes).
// level: 1 = straightforward … 4 = wordplay / lateral.

export type Group = { id: string; name: string; level: 1 | 2 | 3 | 4; members: string[]; also?: string[]; tags: string[] };

const g = (id: string, level: Group['level'], name: string, members: string, tags: string, also = ''): Group => ({
  id,
  name,
  level,
  members: members.split(',').map((s) => s.trim().toUpperCase()).filter(Boolean),
  also: also.split(',').map((s) => s.trim().toUpperCase()).filter(Boolean),
  tags: tags.split(',').map((s) => s.trim()).filter(Boolean),
});

